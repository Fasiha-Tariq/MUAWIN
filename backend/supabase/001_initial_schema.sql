REVOKE ALL ON TABLE ai_clo_mapping FROM anon, authenticated;

ALTER TABLE ai_course_outline ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE ai_course_outline FROM anon, authenticated;

ALTER TABLE ai_class_schedule ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE ai_class_schedule FROM anon, authenticated;

ALTER TABLE course_setup ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE course_setup FROM anon, authenticated;

ALTER TABLE weekly_expectations ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE weekly_expectations FROM anon, authenticated;

ALTER TABLE reminders ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE reminders FROM anon, authenticated;

ALTER TABLE folder_candidates ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE folder_candidates FROM anon, authenticated;

ALTER TABLE operation_events ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE operation_events FROM anon, authenticated;

ALTER TABLE class_sessions ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE class_sessions FROM anon, authenticated;

ALTER TABLE class_chunks ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE class_chunks FROM anon, authenticated;

ALTER TABLE class_segments ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE class_segments FROM anon, authenticated;

ALTER TABLE class_segment_events ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE class_segment_events FROM anon, authenticated;

ALTER TABLE class_suggestions ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE class_suggestions FROM anon, authenticated;

ALTER TABLE class_workflows ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE class_workflows FROM anon, authenticated;

ALTER TABLE audit_events ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE audit_events FROM anon, authenticated;

COMMIT;
