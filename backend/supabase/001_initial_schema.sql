-- MUAWIN PostgreSQL schema. Apply once through the Supabase SQL editor or Management API.
-- User authentication and course ownership checks are enforced by the MUAWIN backend.
BEGIN;

CREATE TABLE IF NOT EXISTS ai_upload_history (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher TEXT NOT NULL, course_key TEXT NOT NULL,
      course TEXT NOT NULL, week INTEGER, item_type TEXT NOT NULL, title TEXT, file_name TEXT,
      weekday INTEGER NOT NULL, uploaded_at TEXT NOT NULL
    );

CREATE INDEX IF NOT EXISTS ix_upload_teacher_course ON ai_upload_history(teacher, course_key);

CREATE TABLE IF NOT EXISTS ai_clo_mapping (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher TEXT NOT NULL, course TEXT NOT NULL,
      week INTEGER, item_type TEXT NOT NULL, title TEXT, clos TEXT, week_clos TEXT,
      llm_clos TEXT, method TEXT, needs_review INTEGER DEFAULT 0, reason TEXT, created_at TEXT NOT NULL
    );

CREATE TABLE IF NOT EXISTS ai_course_outline (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher TEXT NOT NULL, course_key TEXT NOT NULL,
      course TEXT NOT NULL, title TEXT, source_name TEXT, data TEXT NOT NULL, uploaded_at TEXT NOT NULL,
      UNIQUE(teacher, course_key)
    );

CREATE TABLE IF NOT EXISTS ai_class_schedule (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher TEXT NOT NULL, course_key TEXT NOT NULL,
      course TEXT NOT NULL, weekday INTEGER NOT NULL, start_time TEXT, end_time TEXT,
      auto_lecture INTEGER DEFAULT 1, auto_assignment INTEGER DEFAULT 0,
      UNIQUE(teacher, course_key, weekday, start_time, end_time)
    );

CREATE TABLE IF NOT EXISTS course_setup (
      teacher TEXT NOT NULL, course_key TEXT NOT NULL, course TEXT NOT NULL,
      folder_path TEXT, timetable_json TEXT, timetable_confirmed INTEGER DEFAULT 0,
      outline_confirmed INTEGER DEFAULT 0, semester_started_at TEXT,
      outline_file_path TEXT, timetable_file_path TEXT,
      updated_at TEXT NOT NULL, PRIMARY KEY(teacher, course_key)
    );

CREATE TABLE IF NOT EXISTS weekly_expectations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher TEXT NOT NULL,
    course_key TEXT NOT NULL,
    course TEXT NOT NULL,
    week INTEGER NOT NULL,
    expected_topic TEXT DEFAULT '',
    due_date TEXT,
    status TEXT DEFAULT 'pending',
    source TEXT DEFAULT 'outline',
    uploaded_at TEXT,
    notes TEXT,
    UNIQUE(teacher, course_key, week)
);

CREATE TABLE IF NOT EXISTS reminders (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher TEXT NOT NULL, course_key TEXT NOT NULL,
      course TEXT NOT NULL, week INTEGER, title TEXT NOT NULL, message TEXT NOT NULL,
      status TEXT DEFAULT 'active', due_at TEXT, snoozed_until TEXT,
      created_at TEXT NOT NULL, updated_at TEXT NOT NULL, dedupe_key TEXT NOT NULL,
      UNIQUE(teacher, dedupe_key)
    );

CREATE TABLE IF NOT EXISTS folder_candidates (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher TEXT NOT NULL, course_key TEXT NOT NULL,
      course TEXT NOT NULL, file_path TEXT NOT NULL, file_name TEXT NOT NULL,
      size_bytes INTEGER DEFAULT 0, modified_at TEXT, status TEXT DEFAULT 'pending',
      created_at TEXT NOT NULL, UNIQUE(teacher, course_key, file_path)
    );

CREATE TABLE IF NOT EXISTS operation_events (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher TEXT NOT NULL, course TEXT,
      event_type TEXT NOT NULL, status TEXT NOT NULL, details TEXT, created_at TEXT NOT NULL
    );

CREATE TABLE IF NOT EXISTS class_sessions (
            id TEXT PRIMARY KEY, teacher TEXT NOT NULL, course_id TEXT NOT NULL,
            course TEXT NOT NULL, timezone TEXT NOT NULL, started_at TEXT NOT NULL,
            ended_at TEXT, schedule_key TEXT, scheduled_end TEXT
        );

CREATE UNIQUE INDEX IF NOT EXISTS class_active_teacher
            ON class_sessions(teacher) WHERE ended_at IS NULL;

CREATE INDEX IF NOT EXISTS class_history ON class_sessions(teacher, course_id, started_at);

CREATE TABLE IF NOT EXISTS class_chunks (
            id TEXT PRIMARY KEY, session_id TEXT NOT NULL REFERENCES class_sessions(id),
            status TEXT NOT NULL DEFAULT 'pending', attempts INTEGER NOT NULL DEFAULT 0,
            retry_at REAL NOT NULL DEFAULT 0, error TEXT, result TEXT
        );

CREATE TABLE IF NOT EXISTS class_segments (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session_id TEXT NOT NULL REFERENCES class_sessions(id),
            text TEXT NOT NULL, timestamp TEXT NOT NULL,
            chunk_id TEXT REFERENCES class_chunks(id)
        );

CREATE INDEX IF NOT EXISTS class_chunks_session ON class_chunks(session_id);

CREATE TABLE IF NOT EXISTS class_segment_events (
            event_id TEXT PRIMARY KEY, segment_id INTEGER NOT NULL REFERENCES class_segments(id)
        );

CREATE INDEX IF NOT EXISTS class_segments_session ON class_segments(session_id, id);

CREATE INDEX IF NOT EXISTS class_segments_unsealed
            ON class_segments(session_id, id) WHERE chunk_id IS NULL;

CREATE TABLE IF NOT EXISTS class_suggestions (
            id TEXT PRIMARY KEY, session_id TEXT NOT NULL REFERENCES class_sessions(id),
            chunk_id TEXT NOT NULL REFERENCES class_chunks(id), payload TEXT NOT NULL,
            decision TEXT NOT NULL DEFAULT 'proposed', review TEXT
        );

CREATE TABLE IF NOT EXISTS class_workflows (
            id TEXT PRIMARY KEY, suggestion_id TEXT NOT NULL REFERENCES class_suggestions(id),
            status TEXT NOT NULL, updated_at TEXT NOT NULL, result TEXT, error TEXT,
            approved_at TEXT, draft TEXT
        );

CREATE TABLE IF NOT EXISTS audit_events (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            created_at TEXT NOT NULL,
            teacher_username TEXT NOT NULL,
            workflow_id TEXT,
            action TEXT NOT NULL,
            status TEXT NOT NULL,
            course TEXT,
            week INTEGER,
            file_name TEXT,
            details TEXT
        );

ALTER TABLE ai_upload_history ADD COLUMN IF NOT EXISTS is_active INTEGER NOT NULL DEFAULT 1;

ALTER TABLE course_setup ADD COLUMN IF NOT EXISTS setup_completed INTEGER DEFAULT 0;

ALTER TABLE course_setup ADD COLUMN IF NOT EXISTS outline_status_ready INTEGER DEFAULT 0;

ALTER TABLE course_setup ADD COLUMN IF NOT EXISTS schedule_status_ready INTEGER DEFAULT 0;

ALTER TABLE ai_upload_history ENABLE ROW LEVEL SECURITY;

