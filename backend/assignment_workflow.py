def find_definition_for_concept(
    concept: str,
    pairs: List[Tuple[str, str]]
) -> str:
    target = normalize(concept)

    for known, sentence in pairs:
        if normalize(known) == target:
            return sentence

    return ""


def concept_tokens(concept: str) -> set:
    """Return meaningful tokens for comparing concept names."""
    return {
        word for word in normalize(concept).split()
        if word not in STOP_WORDS and len(word) > 1
    }


def concepts_are_related(first: str, second: str) -> bool:
    """
    Detect duplicate or near-duplicate concept labels.

    Examples:
        GE McKinsey
        GE-McKinsey 9-Box Matrix

    These should not normally be treated as two independent topics.
    """
    a = normalize(first)
    b = normalize(second)

    if not a or not b:
        return False

    if a == b:
        return True

    # Detect one normalized phrase occurring inside the other.
    if f" {a} " in f" {b} " or f" {b} " in f" {a} ":
        return True

    ta = concept_tokens(first)
    tb = concept_tokens(second)

    if not ta or not tb:
        return False

    # Avoid retaining a short label when its meaningful words are
    # already covered by a longer concept.
    if len(ta) >= 2 and ta.issubset(tb):
        return True

    if len(tb) >= 2 and tb.issubset(ta):
        return True

    # High token overlap is a signal of a likely duplicate, not proof.
    overlap = len(ta & tb) / len(ta | tb)
    return overlap >= 0.80


def select_distinct_concepts(lecture: str) -> List[str]:
    """
    Select ranked concepts while removing closely related labels.

    The existing extract_concepts() function supplies the ranking.
    This function filters its output instead of changing the parser.
    """
    candidates = extract_concepts(lecture)
    selected: List[str] = []

    for candidate in candidates:
        candidate = clean_concept(candidate)

        if not candidate or not is_good_concept(candidate):
            continue

        if any(
            concepts_are_related(candidate, existing)
            for existing in selected
        ):
            continue

        selected.append(candidate)

    return selected


def find_evidence_for_concept(concept: str, lecture: str) -> str:
    """
    Find a sentence that discusses the concept.

    Returns an empty string when there is no reasonably matching sentence.
    """
    target = normalize(concept)
    target_tokens = concept_tokens(concept)

    best_sentence = ""
    best_score = 0.0

    for sentence in extract_sentences(lecture):
        normalized_sentence = normalize(sentence)

        if target and f" {target} " in f" {normalized_sentence} ":
            return sentence

        sentence_tokens = set(normalized_sentence.split())
        if not target_tokens:
            continue

        overlap = len(target_tokens & sentence_tokens) / len(target_tokens)

        if overlap > best_score and overlap >= 0.60:
            best_score = overlap
            best_sentence = sentence

    return best_sentence


def choose_concept(concepts: List[str], index: int) -> str:
    if not concepts:
        raise ValueError(
            "No distinct concepts were extracted from the lecture."
        )

    return concepts[index % len(concepts)]


def create_question_text(
    qtype: str,
    concept: str,
    definition: str,
    evidence: str = "",
) -> str:
    """
    Create a question using a concept and, where available,
    evidence extracted from the lecture.

    These are rule-based prompts, not LLM-generated answers.
    """
    if qtype == "short":
        if definition:
            return (
                f"According to the lecture, what is {concept}? "
                "State its main purpose."
            )

        if evidence:
            return (
                f"Explain the meaning of {concept} as presented "
                "in the lecture."
            )

        return (
            f"What does the lecture discuss about {concept}? "
            "Give a concise explanation."
        )

    if qtype == "long":
        if definition or evidence:
            return (
                f"Explain {concept} in detail using the lecture material. "
                "Discuss the relevant points and explain their importance."
            )

        return (
            f"Explain {concept} in detail. Relate your answer to the "
            "relevant concepts covered in the lecture."
        )

    if qtype == "scenario":
        return (
            f"Describe a suitable real-world situation in which "
            f"{concept} is relevant. Explain how the concept could "
            "be applied and justify your reasoning using the lecture."
        )

    if qtype == "practical":
        return (
            f"Describe a practical approach for applying {concept}. "
            "Explain the steps and relevant considerations using "
            "the lecture material."
        )

    raise ValueError(f"Unsupported question type: {qtype}")


def generate_rule_based(
    lecture: str,
    plan: List[Tuple[str, int]]
) -> List[GeneratedQuestion]:
    """
    Generate the requested question types using distinct concepts.

    If there are too few distinct concepts, stop instead of silently
    repeating topics in an assignment presented as lecture-based.
    """
    lecture = clean_text(lecture)

    if not lecture:
        raise ValueError("Lecture text is empty.")

    concepts = select_distinct_concepts(lecture)

    if not concepts:
        raise ValueError(
            "Could not extract meaningful concepts from the lecture. "
            "Check whether the file contains readable text. Scanned "
            "PDFs may require OCR."
        )

    required = len(plan)

    if len(concepts) < required:
        raise ValueError(
            f"The lecture yielded only {len(concepts)} distinct concepts, "
            f"but {required} questions were requested. "
            "MUAWIN stopped to avoid repeating topics. Check the extracted "
            "lecture text or use a more complete lecture file."
        )

    definition_pairs = extract_definition_concepts(lecture)
    questions: List[GeneratedQuestion] = []

    for index, (qtype, marks) in enumerate(plan):
        concept = concepts[index]
        definition = find_definition_for_concept(
            concept, definition_pairs
        )
        evidence = find_evidence_for_concept(concept, lecture)

        question_text = create_question_text(
            qtype=qtype,
            concept=concept,
            definition=definition,
            evidence=evidence,
        )

        questions.append(
            GeneratedQuestion(
                number=index + 1,
                question_type=qtype,
                question=question_text,
                marks=marks,
            )
        )

    # Final safety checks.
    if len(questions) != required:
        raise RuntimeError(
            "Generated question count does not match the requested count."
        )

    if sum(q.marks for q in questions) != sum(m for _, m in plan):
        raise RuntimeError(
            "Generated question marks do not match the planned marks."
        )

    return questions
