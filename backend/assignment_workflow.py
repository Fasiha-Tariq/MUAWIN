    def _read_url(self, url: str, depth: int = 0) -> str:
        # Moodle "URL" activity -> follow to the external link (Google Drive etc.)
        if "/mod/url/" in url and depth == 0:
            return self._read_external(url)

        resp = self.ctx.request.get(url, timeout=60000)
        if not resp.ok:
            raise RuntimeError(f"HTTP {resp.status}")
        body = resp.body()
        text = bytes_to_text(body)
        if text:
            return text

        ctype = (resp.headers.get("content-type") or "").lower()
        if "html" in ctype and depth == 0:
            page_html = body.decode("utf-8", "ignore")
            links = []
            for h in re.findall(
                    r"""(?:href|data|src)=["']([^"']*pluginfile\.php[^"']*)["']""", page_html):
                full = urljoin(resp.url, html_lib.unescape(h))
                if full not in links:
                    links.append(full)
            collected = []
            for full in links:
                try:
                    t = self._read_url(full, 1)
                except Exception:
                    continue
                if t.strip():
                    collected.append(t)
                    if "/mod/folder/" not in url:
                        break          # a normal resource: first readable file is enough
                    if len(collected) >= 3:
                        break          # a folder: read a few files
            if collected:
                return "\n\n".join(collected)
            return self._read_rendered_page(url)
        return ""

    def _read_external(self, moodle_url: str) -> str:
        """Moodle URL activity. Works for PUBLIC / link-shared Google files only."""
        sep = "&" if "?" in moodle_url else "?"
        resp = self.ctx.request.get(moodle_url + sep + "redirect=1", timeout=60000)
        final = resp.url
        target = google_export_url(final) or final
        if target != resp.url:
            resp = self.ctx.request.get(target, timeout=60000)
        if not resp.ok:
            raise RuntimeError(f"external link HTTP {resp.status} ({final})")
        text = bytes_to_text(resp.body())
        if not text:
            raise RuntimeError(f"external link is not a readable PDF/Office file or is "
                               f"not shared publicly ({final})")
        return text

    def _read_rendered_page(self, url: str) -> str:
        back = self.page.url
        try:
            self.page.goto(url, wait_until="domcontentloaded", timeout=30000)
            self.page.wait_for_timeout(800)
            main = self.page.locator("[role='main'], #region-main")
            node = main.first if main.count() > 0 else self.page.locator("body")
            return node.inner_text(timeout=10000).strip()
        finally:
            try:
                self.page.goto(back, wait_until="domcontentloaded", timeout=30000)
                self.page.wait_for_timeout(600)
            except Exception:
                pass

    def material_links(self, section) -> List[Tuple[str, str]]:
        return [(t, h) for t, h in self.section_activities(section)
                if any(x in h for x in MATERIAL_URL_HINTS)]

    def find_lecture_by_number(self, number: int) -> List[Tuple[str, str, int]]:
        """Search the WHOLE course for material whose name says 'Lecture N'."""
        pat = re.compile(rf"\blecture\s*(?:no\.?|number|#)?\s*0*{number}\b", re.I)
        hits = []
        for s in self.list_sections():
            for text, href in self.section_activities(s["el"]):
                if any(x in href for x in MATERIAL_URL_HINTS) and pat.search(text):
                    hits.append((text, href, s["num"]))
        return hits

    def find_lecture_by_name(self, name: str) -> List[Tuple[str, str, int]]:
        """Search the WHOLE course for material whose Moellim name contains `name`."""
        target = norm_text(name)
        hits = []
        for s in self.list_sections():
            for text, href in self.section_activities(s["el"]):
                if any(x in href for x in MATERIAL_URL_HINTS) and target in norm_text(text):
                    hits.append((text, href, s["num"]))
        return hits

    def material_names(self, limit: int = 25) -> str:
        names = []
        for s in self.list_sections():
            for text, href in self.section_activities(s["el"]):
                if any(x in href for x in MATERIAL_URL_HINTS) and text:
                    names.append(f"{text} (section-{s['num']})")
        return " | ".join(names[:limit]) or "none"

    def read_materials(self, candidates: List[Tuple[str, str]], label: str,
                       max_materials: int = 3) -> str:
        print()
        line()
        print(f"READING LECTURE MATERIAL - {label}")
        line()
        parts = []
        for text, href in candidates:
            if len(parts) >= max_materials:
                break
            try:
                print(f"  Reading: {text or href}")
                content = self._read_url(href)
                if len(content.strip()) >= 80:
                    parts.append(content.strip())
                else:
                    print("  ! Too little readable text (scanned PDF/images?), skipped.")
            except Exception as exc:
                print(f"  ! Could not read: {exc}")
        if not parts:
            raise RuntimeError(f"Lecture/material could not be extracted from {label}.")
        content = "\n\n".join(parts)[:80000]
        print(f"✓ Lecture content extracted ({len(content)} characters, {len(parts)} file(s)).")
        return content

    def extract_lecture(self, source: Dict, target_week: int, target_section) -> Tuple[str, str]:
        """Returns (lecture_text, human readable source label)."""
        if source.get("lecture"):
            n = source["lecture"]
            hits = self.find_lecture_by_number(n)
            if not hits:
                raise RuntimeError(
                    f"No material named 'Lecture {n}' was found anywhere in this course.\n"
                    f"Materials found: {self.material_names()}\n"
                    "Check the file name on Moellim, or say 'from the Week N lecture' instead.")
            label = f"Lecture {n} (found in section-{hits[0][2]})"
            return self.read_materials([(t, h) for t, h, _ in hits], label), label

        if source.get("name"):
            nm = source["name"]
            hits = self.find_lecture_by_name(nm)
            if not hits:
                raise RuntimeError(
                    f"No material named '{nm}' was found in this course.\n"
                    f"Materials found: {self.material_names()}\n"
                    "Write the name exactly as it appears on Moellim.")
            label = f"'{nm}' (found in section-{hits[0][2]})"
            return self.read_materials([(t, h) for t, h, _ in hits], label), label

        if source.get("week"):
            sw = source["week"]
            el, info = self.find_week_section(sw, quiet=True)
            label = f"Week {sw} [{info['heading'] or 'untitled'}]"
            links = self.material_links(el)
            if not links:
                seen = " | ".join(t for t, _ in self.section_activities(el)) or "nothing"
                raise RuntimeError(f"No lecture/material link found inside Week {sw}.\n"
                                   f"Activities seen there: {seen}")
            return self.read_materials(links, label), label

        links = self.material_links(target_section)
        label = f"Week {target_week} (same week)"
        if not links:
            seen = " | ".join(t for t, _ in self.section_activities(target_section)) or "nothing"
            raise RuntimeError(
                f"No lecture/material link found inside Week {target_week}.\n"
                f"Activities seen there: {seen}\n"
                "TIP: if the lecture is in another week or has a name, say it in the request:\n"
                "     '... from the Week 3 lecture'   or   '... from Lecture 1'")
        return self.read_materials(links, label), label

