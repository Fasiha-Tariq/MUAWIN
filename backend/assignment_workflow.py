def extract_course_id(url: str) -> Optional[str]:
    m = re.search(r"[?&]id=(\d+)", url or "")
    return m.group(1) if m else None


def find_course_id_from_data(course_name: str) -> Optional[str]:
    data_file = ROOT_DIR / "data" / "courses_enriched.json"
    if not data_file.exists():
        return None
    try:
        data = json.loads(data_file.read_text(encoding="utf-8"))
    except Exception:
        return None
    target = norm_text(course_name)
    for course in data:
        for key in ("actual_name", "name", "dashboard_name", "course_name"):
            if course.get(key) and norm_text(course[key]) == target and course.get("id") is not None:
                return str(course["id"])
    return None


def discover_course_id_live(page, course_name: str) -> str:
    target = norm_text(course_name)
    print()
    print("Searching Moellim for exact course...")
    exact, partial = {}, {}

    for url in (f"{MOELLIM_BASE_URL}/my/courses.php",
                f"{MOELLIM_BASE_URL}/my/",
                f"{MOELLIM_BASE_URL}/course/"):
        try:
            page.goto(url, wait_until="domcontentloaded", timeout=30000)
            page.wait_for_timeout(2000)
        except Exception:
            continue
        links = page.locator("a[href*='course/view.php?id=']")
        for i in range(links.count()):
            try:
                text = (links.nth(i).text_content(timeout=1500) or "").strip()
                cid = extract_course_id(urljoin(page.url, links.nth(i).get_attribute("href")))
            except Exception:
                continue
            if not text or not cid:
                continue
            n = norm_text(text)
            if n == target:
                exact[cid] = text
            elif target in n:
                partial[cid] = text
        if exact:
            break

    found = exact or partial
    if not found:
        raise RuntimeError(f"Exact course could not be discovered: {course_name}\n"
                           "MUAWIN stopped before creating anything.")
    if len(found) > 1:
        for cid, text in found.items():
            print(f"  ID={cid} | {text}")
        raise RuntimeError("Course selection is ambiguous. MUAWIN will not guess.")
    cid = next(iter(found))
    print(f"✓ Course discovered. ID: {cid}")
    return cid


def resolve_course_id(page, course_name: str) -> str:
    cid = find_course_id_from_data(course_name)
    if cid:
        print(f"✓ Course found in courses_enriched.json (ID {cid})")
        return cid
    return discover_course_id_live(page, course_name)


