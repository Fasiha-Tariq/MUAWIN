def generate_assignment(lecture_content: str, total_marks: int,
                        question_types) -> List[GeneratedQuestion]:
    """Exactly the requested types/quantities. Nothing extra is added."""
    lecture_content = clean_text(lecture_content)
    if not lecture_content:
        raise ValueError("Lecture content is empty. Cannot generate assignment.")
    types = normalize_question_types(question_types)
    if not types:
        raise ValueError("No question types were specified.")

    marks = distribute_marks(total_marks, types)
    plan: List[Tuple[str, int]] = []
    k = 0
    for qtype, count in types.items():
        for _ in range(count):
            plan.append((qtype, marks[k]))
            k += 1

    qs = generate_rule_based(lecture_content, plan)
    print("✓ Questions generated by the rule-based generator.")
    return qs


def format_assignment_description(questions: List[GeneratedQuestion], instructions: str = "") -> str:
    """Kept for compatibility (v3 puts the questions in the PDF instead)."""
    if not questions:
        raise ValueError("No questions available.")
    esc = html_lib.escape
    parts = []
    if instructions:
        parts.append(f"<p><strong>Instructions:</strong> {esc(instructions)}</p>")
    parts.append("<ol>")
    for q in questions:
        parts.append(f"<li><strong>[{esc(q.question_type.capitalize())}]</strong> "
                     f"{esc(q.question)} <strong>({q.marks} marks)</strong></li>")
    parts.append("</ol>")
    parts.append(f"<p><strong>Total Marks: {sum(q.marks for q in questions)}</strong></p>")
    return "\n".join(parts)


def questions_to_text(questions: List[GeneratedQuestion]) -> str:
    lines = [f"Q{q.number}. [{q.question_type.capitalize()}] {q.question} ({q.marks} marks)"
             for q in questions]
    lines += ["", f"Total Marks: {sum(q.marks for q in questions)}"]
    return "\n".join(lines)


