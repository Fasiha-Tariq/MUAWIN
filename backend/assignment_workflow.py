    def _assign_ids_in(self, section, title: str) -> Dict[str, str]:
        found = {}
        target_title = norm_text(title)

        for text, href in self.section_activities(section, mod="assign"):
            match = re.search(r"[?&]id=(\d+)", href)
            if match and target_title in norm_text(text):
                found[match.group(1)] = text

        return found

    def snapshot_before(self, draft: Dict) -> set:
        """Record matching assignment IDs before creating the assignment."""
        self.page.goto(
            self.course_url,
            wait_until="domcontentloaded",
            timeout=30000,
        )
        self.page.wait_for_timeout(1000)

        self.verify_course(draft["course"])

        section, _info = self.find_week_section(draft["week_number"])
        self.section_num = self.week_info["num"]

        existing_ids = set(
            self._assign_ids_in(section, draft["title"]).keys()
        )

        print(
            "Existing assignments with this title in the target week: "
            f"{len(existing_ids)}"
        )
        return existing_ids

    def verify_saved(self, draft: Dict, before: set) -> None:
        """Verify the new assignment, its settings, location and PDF."""
        print()
        print("Verifying saved assignment...")

        self.page.goto(
            self.course_url,
            wait_until="domcontentloaded",
            timeout=30000,
        )
        self.page.wait_for_timeout(1200)

        section, _info = self.find_week_section(
            draft["week_number"],
            quiet=True,
        )

        if self.week_info["num"] != self.section_num:
            raise RuntimeError(
                "SAME-WEEK VERIFICATION FAILED: the target section changed."
            )

        after = self._assign_ids_in(section, draft["title"])
        new_ids = [item_id for item_id in after if item_id not in before]

        if not new_ids:
            raise RuntimeError(
                f"SAME-WEEK VERIFICATION FAILED: "
                f"'{draft['title']}' was not found in "
                f"Week {draft['week_number']}."
            )

        cmid = new_ids[0]
        print(
            f"✓ Assignment found in Week {draft['week_number']} "
            f"(activity ID {cmid})."
        )

        # Reopen the activity settings to verify saved values.
        self.page.goto(
            f"{MOELLIM_BASE_URL}/course/modedit.php?update={cmid}",
            wait_until="domcontentloaded",
            timeout=30000,
        )
        self.page.wait_for_timeout(1500)
        self.expand_all()

        self.verify_form(draft, "after save")

        section_field = self.page.locator("input[name='section']")
        if (
            section_field.count() > 0
            and section_field.first.input_value() != str(self.section_num)
        ):
            raise RuntimeError(
                "SAME-WEEK VERIFICATION FAILED: saved section differs "
                "from the requested section."
            )

        # Check that the saved description contains the marks information.
        description_field = self.page.locator("#id_introeditor")
        if description_field.count() > 0:
            saved_description = description_field.first.input_value()
            if "total marks" not in norm_text(saved_description):
                raise RuntimeError(
                    "DESCRIPTION CHECK FAILED: saved description does not "
                    "contain the expected total-marks information."
                )

        self.verify_attachment(draft["pdf_path"])

        # Leave the browser on the course page after verification.
        self.page.goto(
            self.course_url,
            wait_until="domcontentloaded",
            timeout=30000,
        )

    def create_approved_assignment(self, draft: Dict) -> None:
        """
        Create the assignment after the backend's approval step.

        The caller must only invoke this method for an approved workflow.
        """
        before = self.snapshot_before(draft)

        self.open_assignment_form(self.section_num)
        self.fill_assignment_settings(draft)
        self.verify_form(draft, "before save")
        self.save_assignment()
        self.verify_saved(draft, before)


