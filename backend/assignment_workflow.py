    @staticmethod
    def _set_value(loc, value: str) -> None:
        """fill(); if the field is still hidden, set it directly with JS."""
        try:
            loc.fill(value, timeout=3000)
        except Exception:
            loc.evaluate("""(el, v) => {
                el.value = v;
                el.dispatchEvent(new Event('input', {bubbles: true}));
                el.dispatchEvent(new Event('change', {bubbles: true}));
            }""", value)

    @staticmethod
    def _select_value(loc, value: str) -> None:
        try:
            loc.select_option(value=value, timeout=3000)
        except Exception:
            loc.evaluate("""(el, v) => {
                el.value = v;
                el.dispatchEvent(new Event('change', {bubbles: true}));
            }""", value)

    @staticmethod
    def _ensure_checked(loc) -> None:
        if loc.count() == 0:
            return
        try:
            if loc.first.is_checked():
                return
        except Exception:
            pass
        try:
            loc.first.check(timeout=3000)
        except Exception:
            loc.first.evaluate("""el => {
                if (!el.checked) {
                    el.checked = true;
                    el.dispatchEvent(new Event('change', {bubbles: true}));
                    el.dispatchEvent(new Event('click', {bubbles: true}));
                }
            }""")

    def set_description(self, html: str) -> None:
        ok = self.page.evaluate(
            """(html) => {
                let done = false;
                const T = window.tinymce || window.tinyMCE;
                try {
                    if (T) {
                        let ed = T.get('id_introeditor');
                        if (!ed && T.editors) {
                            ed = T.editors.find(e => (e.id || '').includes('introeditor'));
                        }
                        if (ed) {
                            ed.setContent(html);
                            ed.save();
                            if (T.triggerSave) T.triggerSave();
                            done = true;
                        }
                    }
                } catch (e) {}
                const atto = document.querySelector('#id_introeditoreditable');
                if (atto) {
                    atto.innerHTML = html;
                    atto.dispatchEvent(new Event('input', {bubbles: true}));
                    done = true;
                }
                const ta = document.querySelector('#id_introeditor');
                if (ta) {
                    ta.value = html;
                    ta.dispatchEvent(new Event('change', {bubbles: true}));
                    done = true;
                }
                return done;
            }""", html)
        if not ok:
            raise RuntimeError("Assignment description editor was not found.")

