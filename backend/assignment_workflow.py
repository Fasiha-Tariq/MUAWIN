    line()
    print(f"Course        : {draft['course']}")
    print(f"Create in     : Week {draft['week_number']}  ->  '{target_info.get('heading') or 'untitled'}'")
    print(f"Week resolved : {target_info.get('method')}")
    print(f"Lecture from  : {draft['source_label']}")
    if activities:
        print("In this week  : " + " | ".join(a for a in activities[:8] if a))
    print(f"Title         : {draft['title']}")
    print(f"Total marks   : {draft['max_grade']}")
    print(f"Deadline      : {fmt_due(draft['duedate'])}")
    print("Questions     : " + ", ".join(f"{c} {t}" for t, c in draft["question_types"].items()))
    print(f"PDF preview   : {draft['pdf_path']}")
    for w in draft.get("warnings", []):
        print(f"⚠ WARNING     : {w}")
    print()
    line("-")
    print(questions_to_text(draft["questions"]))
    line("-")
    print("ENTER = Approve and create | E = edit title | N = cancel")

    choice = input("\nTeacher choice: ").strip().lower()
    if choice == "n":
        return False
    if choice == "e":
        new_title = input(f"Title [{draft['title']}]: ").strip()
        if new_title:
            draft["title"] = new_title
        if input("ENTER = approve, N = cancel: ").strip().lower() == "n":
            return False
    return True


