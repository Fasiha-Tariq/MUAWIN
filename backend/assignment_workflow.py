def prepare_assignment_request(page, instruction: str) -> Dict:
    """
    Prepare an assignment for the MUAWIN API.

    This function does not save anything or request terminal approval.
    The backend handles login and teacher approval.
    """
    parsed = parse_request(instruction)
    validate_parsed_request(parsed)

    # The integrated backend authenticates before calling this function.
    # Do not call login_to_moellim(page) again here.
    course_id = resolve_course_id(page, parsed["course"])

    auto = AssignmentAutomation(page)
    auto.open_course(course_id)
    auto.verify_course(parsed["course"])

    # Resolve an existing target week. Never create a new section.
    target_section, target_info = auto.find_week_section(parsed["week"])
    activities = [
        text for text, _href in auto.section_activities(target_section)
    ]

    # Read the requested lecture or material.
    lecture, source_label = auto.extract_lecture(
        parsed["source"],
        parsed["week"],
        target_section,
    )

    questions = generate_assignment(
        lecture_content=lecture,
        total_marks=parsed["max_grade"],
        question_types=parsed["question_types"],
    )

    if sum(question.marks for question in questions) != parsed["max_grade"]:
        raise RuntimeError(
            "Generated question marks do not match the requested total."
        )

    warnings = []

    if len(lecture) < 1500:
        warnings.append(
            f"Lecture text is short ({len(lecture)} characters). "
            "Review the generated questions carefully."
        )

    if len(extract_concepts(lecture)) < len(questions):
        warnings.append(
            "The lecture has fewer distinct topics than questions; "
            "some topics may repeat."
        )

    draft = {
        "warnings": warnings,
        "course": parsed["course"],
        "week_number": parsed["week"],
        "title": parsed["title"],
        "max_grade": parsed["max_grade"],
        "duedate": parsed["duedate"],
        "question_types": parsed["question_types"],
        "questions": questions,
        "source_label": source_label,
        "description": short_description(parsed["max_grade"]),
    }

    # Generate a PDF preview before teacher approval.
    draft["pdf_path"] = str(make_assignment_pdf(draft))

    return {
        "status": "waiting_approval",
        "parsed": parsed,
        "draft": draft,
        "automation": auto,
        "course_id": str(course_id),
        "target_info": target_info,
        "activities": activities,
    }


def execute_prepared_assignment(workflow: Dict) -> Dict:
    """
    Execute a prepared assignment.

    The integrated backend should call this only after its approval route
    has changed the workflow status to 'approved'.
    """
    if workflow.get("status") != "approved":
        raise RuntimeError(
            "Assignment execution blocked: the workflow has not been "
            "approved by the teacher."
        )

    draft = workflow.get("draft")
    auto = workflow.get("automation")

    if not isinstance(draft, dict) or auto is None:
        raise RuntimeError(
            "Assignment execution failed: prepared draft or browser "
            "automation object is missing."
        )

    # Rebuild the PDF from the approved draft, including any edited title.
    draft["pdf_path"] = str(make_assignment_pdf(draft))

    # Save and verify using the methods defined on AssignmentAutomation.
    auto.create_approved_assignment(draft)

    return {
        "status": "success",
        "course": draft["course"],
        "course_id": str(workflow["course_id"]),
        "week": f"Week {draft['week_number']}",
        "moodle_section": dict(auto.week_info),
        "lecture_source": draft["source_label"],
        "title": draft["title"],
        "pdf_file": str(draft["pdf_path"]),
        "max_grade": draft["max_grade"],
        "duedate": draft["duedate"].isoformat(),
        "question_types": draft["question_types"],
        "question_count": len(draft["questions"]),
        "questions": [
            question.__dict__ for question in draft["questions"]
        ],
        "message": (
            "Assignment created with its PDF attached and the saved "
            "assignment verified."
        ),
    }

