TYPE_WEIGHT = {"short": 1, "scenario": 2, "practical": 2, "long": 3}


def distribute_marks(total_marks: int, question_types: Dict[str, int]) -> List[int]:
    """
    One mark value per question, in the order of question_types.
    Prefers the same marks for every question of one type, harder types
    never worth less than easier ones, sum is exactly total_marks.
    """
    types = list(question_types.items())
    n = sum(c for _, c in types)
    if n <= 0:
        raise ValueError("At least one question is required.")
    if total_marks <= 0:
        raise ValueError("Total marks must be greater than zero.")
    if total_marks < n:
        raise ValueError(f"Total marks ({total_marks}) cannot be less than "
                         f"number of questions ({n}).")

    weights = [TYPE_WEIGHT.get(t, 1) for t, _ in types]
    unit = total_marks / sum(w * c for w, (_, c) in zip(weights, types))
    ideal = [w * unit for w in weights]

    best: Dict = {"score": None, "combo": None}

    def search(i: int, remaining: int, chosen: List[int]) -> None:
        if i == len(types) - 1:
            count = types[i][1]
            if remaining < count or remaining % count:
                return
            combo = chosen + [remaining // count]
            for a in range(len(types)):
                for b in range(len(types)):
                    if weights[a] > weights[b] and combo[a] < combo[b]:
                        return
            score = sum(types[k][1] * (combo[k] - ideal[k]) ** 2 for k in range(len(types)))
            if best["score"] is None or score < best["score"]:
                best["score"], best["combo"] = score, combo
            return
        count = types[i][1]
        min_rest = sum(c for _, c in types[i + 1:])
        m = 1
        while m * count + min_rest <= remaining:
            search(i + 1, remaining - m * count, chosen + [m])
            m += 1

    search(0, total_marks, [])
    if best["combo"]:
        marks: List[int] = []
        for (_, count), m in zip(types, best["combo"]):
            marks += [m] * count
        return marks

    # Fallback: weighted largest-remainder per question.
    per_q = [w for w, (_, c) in zip(weights, types) for _ in range(c)]
    raw = [w * total_marks / sum(per_q) for w in per_q]
    marks = [max(1, int(r)) for r in raw]
    diff = total_marks - sum(marks)
    order = sorted(range(n), key=lambda k: raw[k] - int(raw[k]), reverse=True)
    i = 0
    while diff > 0:
        marks[order[i % n]] += 1
        diff -= 1
        i += 1
    while diff < 0:
        j = max((k for k in range(n) if marks[k] > 1), key=lambda k: marks[k])
        marks[j] -= 1
        diff += 1
    return marks


