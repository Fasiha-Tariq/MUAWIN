def pdf_to_text(data: bytes) -> str:
    try:
        from pypdf import PdfReader
    except ImportError:
        raise RuntimeError("pypdf is not installed. Run: python -m pip install pypdf")
    reader = PdfReader(io.BytesIO(data))
    pages = []
    for p in reader.pages:
        try:
            t = (p.extract_text() or "").strip()
            if t:
                pages.append(t)
        except Exception:
            continue
    return "\n\n".join(pages).strip()


def office_to_text(data: bytes) -> str:
    """DOCX / PPTX without extra libraries."""
    import zipfile
    try:
        z = zipfile.ZipFile(io.BytesIO(data))
    except zipfile.BadZipFile:
        return ""
    names = z.namelist()
    out = []
    if "word/document.xml" in names:
        xml = z.read("word/document.xml").decode("utf-8", "ignore")
        for para in re.findall(r"<w:p[ >].*?</w:p>", xml, flags=re.S):
            t = "".join(re.findall(r"<w:t[^>]*>(.*?)</w:t>", para, flags=re.S))
            if t.strip():
                out.append(html_lib.unescape(t))
    else:
        slides = sorted(
            (n for n in names if re.fullmatch(r"ppt/slides/slide\d+\.xml", n)),
            key=lambda n: int(re.search(r"(\d+)", n.split("/")[-1]).group(1)))
        for n in slides:
            xml = z.read(n).decode("utf-8", "ignore")
            texts = re.findall(r"<a:t>(.*?)</a:t>", xml, flags=re.S)
            if texts:
                out.append("\n".join(html_lib.unescape(t) for t in texts))
    return "\n\n".join(out).strip()


def bytes_to_text(body: bytes) -> str:
    if body[:4] == b"%PDF":
        return pdf_to_text(body)
    if body[:2] == b"PK":
        return office_to_text(body)
    return ""


def local_file_to_text(path: Path) -> str:
    data = path.read_bytes()
    text = bytes_to_text(data)
    if text:
        return text
    return data.decode("utf-8", "ignore")


def google_export_url(url: str) -> Optional[str]:
    """Public Google Drive / Docs / Slides links -> direct download URL."""
    m = re.search(r"drive\.google\.com/file/d/([\w-]+)", url) or \
        re.search(r"drive\.google\.com/open\?id=([\w-]+)", url)
    if m:
        return f"https://drive.google.com/uc?export=download&id={m.group(1)}"
    m = re.search(r"docs\.google\.com/(document|presentation|spreadsheets)/d/([\w-]+)", url)
    if m:
        return f"https://docs.google.com/{m.group(1)}/d/{m.group(2)}/export/pdf"
    return None


