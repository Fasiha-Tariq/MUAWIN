    def set_date(self, prefix: str, when: datetime) -> None:
        self._ensure_checked(self.page.locator(f"#id_{prefix}_enabled"))
        values = {"day": when.day, "month": when.month, "year": when.year,
                  "hour": when.hour, "minute": when.minute}
        for field, value in values.items():
            loc = self.page.locator(f"#id_{prefix}_{field}")
            if loc.count() > 0:
                self._select_value(loc.first, str(value))

    def read_date(self, prefix: str) -> Optional[Tuple[int, int, int, int, int]]:
        vals = {}
        for field in ("day", "month", "year", "hour", "minute"):
            loc = self.page.locator(f"#id_{prefix}_{field}")
            if loc.count() == 0:
                return None
            vals[field] = int(loc.first.input_value())
        return vals["year"], vals["month"], vals["day"], vals["hour"], vals["minute"]

