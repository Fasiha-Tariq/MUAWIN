def run_assignment_request(page, course_id: str, parsed: Dict,
                           auto_approve: bool = False) -> Dict:
    auto = AssignmentAutomation(page)
    auto.open_course(course_id)
    auto.verify_course(parsed["course"])

    # 1) the week where the assignment will be CREATED
    target_section, target_info = auto.find_week_section(parsed["week"])
    activities = [t for t, _ in auto.section_activities(target_section)]

    # 2) the lecture the questions come from (same week, other week, or Lecture N)
    lecture, source_label = auto.extract_lecture(parsed["source"], parsed["week"], target_section)

    print()
    line()
    print("GENERATING QUESTIONS FROM THE LECTURE")
    line()
    questions = generate_assignment(
        lecture_content=lecture,
        total_marks=parsed["max_grade"],
        question_types=parsed["question_types"],
    )
    if sum(q.marks for q in questions) != parsed["max_grade"]:
        raise RuntimeError("Generated marks do not match the requested total marks.")

    warnings = []
    if len(lecture) < 1500:
        warnings.append(f"Lecture text is very short ({len(lecture)} characters). It may be only a "
                        "cover page or scanned slides, so the questions can be weak.")
    n_questions = sum(parsed["question_types"].values())
    if len(extract_concepts(lecture)) < n_questions:
        warnings.append("The lecture has fewer distinct topics than questions, so topics will repeat.")

    draft = {
        "warnings": warnings,
        "course": parsed["course"],
        "week_number": parsed["week"],
        "title": parsed["title"],
        "max_grade": parsed["max_grade"],
        "duedate": parsed["duedate"],
        "question_types": parsed["question_types"],
        "questions": questions,
        "source_label": source_label,
        # questions live in the PDF; the description is only a short pointer
        "description": short_description(parsed["max_grade"]),
    }

    # PDF is built BEFORE the review so the teacher can open and check it.
    draft["pdf_path"] = make_assignment_pdf(draft)
    print(f"✓ Assignment PDF created: {draft['pdf_path']}")

    if auto_approve:
        print("⚠ Auto-approve enabled.")
        for w in warnings:
            print(f"⚠ WARNING: {w}")
    elif not assignment_review(draft, target_info, activities):
        return {"status": "cancelled", "message": "Teacher cancelled assignment."}

    # rebuild once more: the teacher may have edited the title in the review
    draft["pdf_path"] = make_assignment_pdf(draft)

    auto.create_approved_assignment(draft)

    print()
    line()
    print("✓ MUAWIN ASSIGNMENT WORKFLOW COMPLETED")
    line()
    print(f"Course {draft['course']} | Week {draft['week_number']} | "
          f"{draft['title']} | {draft['max_grade']} marks | {fmt_due(draft['duedate'])}")
    print("Verification: Course ✓ | Grade ✓ | Deadline ✓ | PDF attached ✓ | Same week ✓")

    return {
        "status": "success",
        "course": draft["course"],
        "course_id": str(course_id),
        "week": parsed["section"],
        "moodle_section": dict(auto.week_info),
        "lecture_source": source_label,
        "title": draft["title"],
        "pdf_file": str(draft["pdf_path"]),
        "max_grade": draft["max_grade"],
        "duedate": draft["duedate"].isoformat(),
        "question_types": draft["question_types"],
        "question_count": len(questions),
        "questions": [q.__dict__ for q in questions],
        "message": "Assignment created (questions attached as PDF) and verified in the requested week.",
    }


def save_result(result: Dict) -> Path:
    folder = ROOT_DIR / "data" / "assignment_results"
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"assignment_{datetime.now():%Y%m%d_%H%M%S}.json"
    path.write_text(json.dumps(result, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    return path


