def main() -> int:
    ap = argparse.ArgumentParser(description="MUAWIN Moellim assignment creator")
    ap.add_argument("--request", type=str, help="Teacher request (otherwise asked once)")
    ap.add_argument("--yes", action="store_true", help="Skip approval (testing only)")
    ap.add_argument("--headless", action="store_true")
    ap.add_argument("--dry-run", action="store_true",
                    help="Parse the request (and, with --lecture-file, generate questions + PDF). No browser.")
    ap.add_argument("--lecture-file", type=str,
                    help="Local PDF/PPTX/DOCX/TXT to test question generation offline (with --dry-run)")
    args = ap.parse_args()

    print()
    line()
    print("MUAWIN - ASSIGNMENT WORKFLOW")
    line()

    request = args.request
    if not request:
        print("Teacher request:")
        request = input("> ").strip()
    if not request:
        print("ERROR: Empty teacher request.")
        return 1

    try:
        parsed = parse_request(request)
        validate_parsed_request(parsed)
    except ValueError as exc:
        print(f"\n✗ {exc}")
        return 1

    print("\n✓ Request understood")
    print(f"  Course      : {parsed['course']}")
    print(f"  Create in   : Week {parsed['week']}")
    print(f"  Lecture from: {describe_source(parsed['source'], parsed['week'])}")
    print(f"  Title       : {parsed['title']}")
    print(f"  Marks       : {parsed['max_grade']}")
    print(f"  Deadline    : {fmt_due(parsed['duedate'])}")
    print(f"  Questions   : {parsed['question_types']}")

    if args.dry_run:
        if args.lecture_file:
            try:
                text = local_file_to_text(Path(args.lecture_file))
                qs = generate_assignment(text, parsed["max_grade"], parsed["question_types"])
                demo = {"title": parsed["title"], "course": parsed["course"],
                        "week_number": parsed["week"], "max_grade": parsed["max_grade"],
                        "duedate": parsed["duedate"], "questions": qs}
                pdf = make_assignment_pdf(demo)
            except Exception as exc:
                print(f"\n✗ {exc}")
                return 1
            print()
            line("-")
            print(questions_to_text(qs))
            line("-")
            print(f"✓ PDF created: {pdf}")
        return 0

    if sync_playwright is None:
        print("\n✗ Playwright is not installed. Run:\n"
              "   python -m pip install playwright python-dotenv pypdf reportlab\n"
              "   python -m playwright install chromium")
        return 1

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        context = browser.new_context()
        page = context.new_page()
        try:
            login_to_moellim(page)
            course_id = resolve_course_id(page, parsed["course"])
            result = run_assignment_request(page, course_id, parsed, auto_approve=args.yes)
            print(f"\nResult saved to: {save_result(result)}")
            return 0 if result.get("status") == "success" else 1
        except KeyboardInterrupt:
            print("\nCancelled by user.")
            return 130
        except Exception as exc:
            print()
            line()
            print("✗ MUAWIN WORKFLOW STOPPED")
            line()
            print(f"Reason: {exc}")
            print("\nNothing is reported as success because a check failed.")
            return 1
        finally:
            for closer in (context.close, browser.close):
                try:
                    closer()
                except Exception:
                    pass


if __name__ == "__main__":
    raise SystemExit(main())