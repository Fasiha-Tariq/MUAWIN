QUESTION_PATTERNS = {
    "short": r"(\d+)\s+(?:short|short[\s-]answer)(?:\s+questions?)?",
    "long": r"(\d+)\s+(?:long|long[\s-]answer)(?:\s+questions?)?",
    "scenario": r"(\d+)\s+(?:scenario|scenario[\s-]based)(?:\s+questions?)?",
    "practical": r"(\d+)\s+(?:practical|application[\s-]based)(?:\s+questions?)?",
}


def parse_question_types(request: str) -> Dict[str, int]:
    result: Dict[str, int] = {}
    for qtype, pattern in QUESTION_PATTERNS.items():
        for m in re.finditer(pattern, request, flags=re.I):
            result[qtype] = result.get(qtype, 0) + int(m.group(1))
    return result


def parse_week(request: str) -> Optional[int]:
    """TARGET week = the first 'Week N' in the request."""
    m = re.search(r"\b(?:week|wk)\s*0*(\d+)\b", request, flags=re.I)
    return int(m.group(1)) if m else None


SOURCE_GENERIC_WORDS = {"the", "this", "that", "week", "weeks", "s", "lecture", "lectures",
                        "material", "materials", "file", "files", "slides", "slide", "pdf",
                        "ppt", "pptx", "notes", "content"}


def parse_source(request: str) -> Dict[str, Optional[object]]:
    """
    Where the lecture comes from:
        from the Week 3 lecture      -> {"week": 3}
        from Lecture 1               -> {"lecture": 1}
        from the MUAWIN TEST LEC     -> {"name": "MUAWIN TEST LEC"}  (file name on Moellim)
        (nothing)                    -> same week as the assignment
    """
    none: Dict[str, Optional[object]] = {"week": None, "lecture": None, "name": None}
    m = re.search(r"\bfrom\s+(?:the\s+)?(?:week|wk)\s*0*(\d+)\b", request, flags=re.I)
    if m:
        return {**none, "week": int(m.group(1))}
    m = re.search(r"\bfrom\s+(?:the\s+)?lecture\s*(?:no\.?|number|#)?\s*0*(\d+)\b",
                  request, flags=re.I)
    if m:
        return {**none, "lecture": int(m.group(1))}
    m = re.search(
        r"\bfrom\s+(?:the\s+)?(?:[\"\u201c']([^\"\u201d']+)[\"\u201d']|(.+?))"
        r"(?=\s*[.,;]?\s*(?:deadline|due|submit)\b|\s*[.;]\s|\s*$)",
        request, flags=re.I | re.S)
    if m:
        name = (m.group(1) or m.group(2) or "").strip(" .,;:")
        qm = re.match(r"^[\"\u201c']([^\"\u201d']+)[\"\u201d']", name)
        if qm:
            name = qm.group(1).strip()
        words = name.split()
        while words and norm_text(words[-1]) in SOURCE_GENERIC_WORDS:
            words.pop()
        name = " ".join(words)
        if name and any(t not in SOURCE_GENERIC_WORDS for t in norm_text(name).split()):
            return {**none, "name": name}
    return none


def parse_marks(request: str) -> Optional[int]:
    for pattern in (r"\b(\d+)\s*(?:total\s*)?marks?\b", r"\bmarks?\s*[:=]\s*(\d+)\b"):
        m = re.search(pattern, request, flags=re.I)
        if m:
            return int(m.group(1))
    return None


def parse_title(request: str) -> Optional[str]:
    m = re.search(
        r"\b(?:titled|title|called|named)\s*[:=]?\s*[\"'\u201c]([^\"'\u201d]+)[\"'\u201d]",
        request, flags=re.I)
    if not m:
        m = re.search(
            r"\b(?:titled|title|called|named)\s*[:=]?\s*(.+?)"
            r"(?=[.;,]\s|\s+(?:due|deadline|with|having|generate|from|and\s+\d+)\b|$)",
            request, flags=re.I)
    if m:
        return m.group(1).strip(" .,;:") or None
    return None



def parse_deadline(request: str) -> Optional[datetime]:
    """
    Supported formats:
      Deadline: 11 October 2026 11:59 PM
      Due: 11 Oct 2026 at 11:59 PM
      Deadline: October 12, 2026
      Deadline: Oct 12, 2026, 11:59 PM
      Deadline: 2026-10-12 23:59

    A date without a time defaults to 11:59 PM.
    """
    m = re.search(
        r"\b(?:due|deadline|submit\s+by|submission\s+deadline)"
        r"\s*[:=]?\s*(?:on\s+)?(.*)",
        request,
        flags=re.I | re.S,
    )
    if not m:
        return None

    tail = m.group(1).strip()

    year = month = day = None
    date_match = None

    # Format: 12 October 2026
    date_match = re.match(
        r"\s*(\d{1,2})(?:st|nd|rd|th)?\s+"
        r"([A-Za-z]{3,9})\.?,?\s+(\d{4})",
        tail,
        flags=re.I,
    )

    if date_match:
        day = int(date_match.group(1))
        month = MONTHS.get(date_match.group(2)[:3].lower())
        year = int(date_match.group(3))

    else:
        # Format: 2026-10-12
        date_match = re.match(
            r"\s*(\d{4})-(\d{2})-(\d{2})",
            tail,
        )

        if date_match:
            year, month, day = (
                int(date_match.group(i))
                for i in (1, 2, 3)
            )

        else:
            # Format: October 12, 2026
            date_match = re.match(
                r"\s*([A-Za-z]{3,9})\.?\s+"
                r"(\d{1,2})(?:st|nd|rd|th)?"
                r"\s*,?\s+(\d{4})",
                tail,
                flags=re.I,
            )

            if date_match:
                month = MONTHS.get(
                    date_match.group(1)[:3].lower()
                )
                day = int(date_match.group(2))
                year = int(date_match.group(3))

    if not date_match or not month:
        return None

    # Date-only deadlines default to 11:59 PM.
    hour, minute = 23, 59

    time_match = re.match(
        r"\s*(?:,|at|@)?\s*"
        r"(\d{1,2})(?::(\d{2}))?\s*(AM|PM)?\b",
        tail[date_match.end():],
        flags=re.I,
    )

    if time_match and (
        time_match.group(2) or time_match.group(3)
    ):
        hour = int(time_match.group(1))
        minute = int(time_match.group(2) or 0)
        period = (
            time_match.group(3).upper()
            if time_match.group(3)
            else None
        )

        if period:
            if not 1 <= hour <= 12:
                return None

            if period == "PM" and hour < 12:
                hour += 12
            elif period == "AM" and hour == 12:
                hour = 0

    try:
        return datetime(year, month, day, hour, minute)
    except (ValueError, TypeError):
        return None

def parse_course(request: str) -> Optional[str]:
    for pattern in (
        r"\bfor\s+course\s+(.+?)(?=\s*,?\s*\b(?:week|wk)\s*\d+\b)",
        r"\bcourse\s*[:=]\s*(.+?)(?=\s*,?\s*\b(?:week|wk)\s*\d+\b)",
        r"\bfor\s+(.+?)(?=\s*,?\s*\b(?:week|wk)\s*\d+\b)",
    ):
        m = re.search(pattern, request, flags=re.I)
        if m:
            course = re.sub(r"\s+(?:to|please|and)\s*$", "", m.group(1).strip(),
                            flags=re.I).strip(" .,;:")
            if course:
                return course
    return None


def parse_request(request: str) -> Dict:
    week = parse_week(request)
    return {
        "course": parse_course(request),
        "week": week,
        "section": f"Week {week}" if week else None,
        "title": parse_title(request),
        "max_grade": parse_marks(request),
        "duedate": parse_deadline(request),
        "question_types": parse_question_types(request),
        "source": parse_source(request),
        "raw_request": request,
    }


def validate_parsed_request(job: Dict) -> None:
    labels = {
        "course": "course", "week": "week", "title": "assignment title",
        "max_grade": "total marks", "duedate": "deadline",
        "question_types": "question types and quantities",
    }
    missing = [label for key, label in labels.items() if not job.get(key)]
    if missing:
        raise ValueError("Request incomplete. Missing: " + ", ".join(missing) + ".")
    if job["max_grade"] <= 0:
        raise ValueError("Total marks must be greater than zero.")
    if job["duedate"] <= datetime.now():
        raise ValueError(f"Deadline must be in the future (got {fmt_due(job['duedate'])}).")
    # fail early if the marks cannot cover the questions
    distribute_marks(job["max_grade"], job["question_types"])


