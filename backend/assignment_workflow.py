_HEADING_NOISE = re.compile(
    r"\b(select section|collapse all|expand all|collapse|expand|current week|"
    r"hidden from students)\b", re.I)


def clean_heading(text: str) -> str:
    t = re.sub(r"\s+", " ", _HEADING_NOISE.sub(" ", text or "")).strip()
    words = t.split()
    half = len(words) // 2
    if half and len(words) % 2 == 0 and words[:half] == words[half:]:
        t = " ".join(words[:half])
    return t


class AssignmentAutomation:

    def __init__(self, page):
        self.page = page
        self.ctx = page.context
        self.week_info: Dict = {}
        self.course_id = ""
        self.course_url = ""
        self.section_num = 0

    # ---------------- course ----------------

    def open_course(self, course_id: str) -> None:
        self.course_id = str(course_id)
        self.course_url = f"{MOELLIM_BASE_URL}/course/view.php?id={course_id}"
        self.page.goto(self.course_url, wait_until="domcontentloaded", timeout=30000)
        self.page.wait_for_timeout(1200)
        print(f"✓ Course page: {self.page.title()}")

    def verify_course(self, expected_course: str) -> None:
        expected = norm_text(expected_course)
        title = norm_text(self.page.title())
        body = norm_text(self.page.locator("body").inner_text(timeout=10000))
        if expected in title or expected in body:
            print(f"✓ Exact course verified: {expected_course}")
            return
        raise RuntimeError(
            "COURSE VERIFICATION FAILED.\n"
            f"Requested: {expected_course}\nActual page: {self.page.title()}\n"
            "MUAWIN will NOT create the assignment.")

    # ---------------- sections / weeks ----------------

    @staticmethod
    def _week_in(text: str) -> Optional[int]:
        m = re.search(r"\b(?:week|wk)\s*0*(\d+)\b", text or "", flags=re.I)
        return int(m.group(1)) if m else None

    def _heading(self, el) -> str:
        for sel in ("[data-for='section_title']", ".sectionname", "h3", "h2", "h4"):
            try:
                loc = el.locator(sel)
                if loc.count() == 0:
                    continue
                text = clean_heading(loc.first.text_content(timeout=1500) or "")
                if text:
                    return text
            except Exception:
                continue
        return ""

    def list_sections(self) -> List[Dict]:
        loc = self.page.locator("li[id^='section-'], div[id^='section-']")
        seen, out = set(), []
        for i in range(loc.count()):
            el = loc.nth(i)
            try:
                m = re.fullmatch(r"section-(\d+)", el.get_attribute("id") or "")
                if not m or int(m.group(1)) in seen:
                    continue
                num = int(m.group(1))
                seen.add(num)
                out.append({"num": num, "el": el, "heading": self._heading(el)})
            except Exception:
                continue
        out.sort(key=lambda s: s["num"])
        return out

    def find_week_section(self, week_number: int, quiet: bool = False):
        """
        Exact week resolution. Never creates a week. Returns (element, info).

        1. A section whose HEADING says 'Week N'.
        2. If NO heading has a week label at all (date-range headings like
           '6 September - 12 September'), Moodle section number N is Week N
           (section-0 is the General block).
        3. Otherwise stop - never guess.
        """
        if not quiet:
            print()
            print(f"Searching for exact Moodle section: Week {week_number}")
        secs = self.list_sections()
        if not secs:
            raise RuntimeError("No Moodle course sections were found.")
        if not quiet:
            print(f"✓ Moodle sections found: {len(secs)}")
            for s in secs[:30]:
                print(f"   section-{s['num']:<3} {s['heading']!r}")

        hits = [s for s in secs if self._week_in(s["heading"]) == week_number]
        if len(hits) > 1:
            raise RuntimeError(f"Week {week_number} appears in {len(hits)} section "
                               "headings. MUAWIN will not guess.")
        if hits:
            chosen, method = hits[0], "heading label"
        else:
            labelled = sorted({self._week_in(s["heading"]) for s in secs
                               if self._week_in(s["heading"]) is not None})
            if labelled:
                raise RuntimeError(f"Section 'Week {week_number}' was not found.\n"
                                   f"This course labels its weeks: {labelled}\n"
                                   "Assignment creation has been stopped.")
            chosen = next((s for s in secs if s["num"] == week_number), None)
            if chosen is None:
                raise RuntimeError(f"Moodle has no section number {week_number}.")
            method = (f"Moodle section number {week_number} "
                      "(course headings carry no 'Week N' label)")

        info = {"num": chosen["num"], "heading": chosen["heading"], "method": method}
        self.week_info = info
        if not quiet:
            print(f"✓ Week {week_number} -> section-{chosen['num']} "
                  f"[{chosen['heading'] or 'no heading'}] via {method}")
        return chosen["el"], dict(info)

    def section_activities(self, section, mod: Optional[str] = None) -> List[Tuple[str, str]]:
        """(text, absolute_url) of activity links inside the section."""
        out, seen = [], set()
        links = section.locator("a[href*='/mod/']")
        for i in range(links.count()):
            try:
                href = urljoin(self.page.url, links.nth(i).get_attribute("href") or "")
                if mod and f"/mod/{mod}/" not in href:
                    continue
                if href in seen or "modedit" in href or "delete" in href:
                    continue
                seen.add(href)
                text = re.sub(r"\s+", " ", links.nth(i).text_content(timeout=1500) or "").strip()
                out.append((text, href))
            except Exception:
                continue
        return out

