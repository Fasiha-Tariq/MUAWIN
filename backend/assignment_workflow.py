def clean_text(text: str) -> str:
    if not text:
        return ""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = []
    for ln in text.split("\n"):
        ln = re.sub(r"\s+", " ", ln).strip()
        if ln:
            lines.append(ln)
    return "\n".join(lines)


def normalize(text: str) -> str:
    text = clean_text(text).lower()
    text = re.sub(r"[^a-z0-9\s]", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def extract_sentences(text: str) -> List[str]:
    text = clean_text(text)
    if not text:
        return []
    out = []
    for chunk in re.split(r"(?<=[.!?])\s+|\n+", text):
        chunk = chunk.strip()
        if chunk and len(re.findall(r"[A-Za-z][A-Za-z\-']*", chunk)) >= 4:
            out.append(chunk)
    return out


def clean_concept(concept: str) -> str:
    concept = re.sub(r"^[\s\-:;,.\d]+|[\s\-:;,.\d]+$", "", (concept or "").strip())
    words = concept.split()
    while words and words[0].lower() in STOP_WORDS:
        words.pop(0)
    while words and words[-1].lower() in STOP_WORDS:
        words.pop()
    result = " ".join(words)
    return result if len(result) >= 3 else ""


GENERIC_START = {"same", "form", "other", "another", "many", "various", "several",
                 "certain", "different", "some", "such", "own", "way", "ways", "number"}

BOILERPLATE_WORDS = {"university", "faculty", "department", "institute", "college",
                     "semester", "instructor", "lecturer", "professor", "riphah", "moellim"}


def is_good_concept(concept: str) -> bool:
    n = normalize(concept)
    if not n or len(n) < 4 or len(n) > 70:
        return False
    words = n.split()
    if any(w in BOILERPLATE_WORDS for w in words) or words[0] in GENERIC_START:
        return False
    if words[0] in BAD_CONCEPT_START or all(w in STOP_WORDS for w in words):
        return False
    if re.search(r"\d{3,}", n):
        return False
    letters = sum(ch.isalpha() for ch in concept)
    return letters >= 0.6 * len(concept)


def unique_concepts(concepts: List[str]) -> List[str]:
    seen, result = set(), []
    for concept in concepts:
        concept = clean_concept(concept)
        if not concept or not is_good_concept(concept):
            continue
        key = normalize(concept)
        if key in seen:
            continue
        seen.add(key)
        result.append(concept)
    return result


def extract_heading_concepts(text: str) -> List[str]:
    concepts: List[str] = []
    for original in clean_text(text).split("\n"):
        cand = re.sub(r"^#{1,6}\s*", "", original.strip())
        cand = re.sub(r"^\s*\d+(?:\.\d+)*[\.)\-:]\s*", "", cand)
        cand = re.sub(r"^\s*[-*\u2022]\s*", "", cand).strip()
        tm = re.match(r"^(?:title|topic|subject)\s*:\s*(.+)$", cand, flags=re.I)
        if tm:
            cand = tm.group(1).strip()
        words = re.findall(r"[A-Za-z][A-Za-z\-']*", cand)
        if len(words) < 2 or len(words) > 12:
            continue
        if cand.endswith((".", "?", "!", ",", ";")):
            continue
        if not cand[:1].isupper() or words[-1].lower() in STOP_WORDS:
            continue       # fragment of a wrapped line
        concepts.append(cand)
    return unique_concepts(concepts)


def extract_definition_concepts(text: str) -> List[Tuple[str, str]]:
    patterns = [
        re.compile(r"^(?P<c>[A-Za-z][A-Za-z0-9\- ]{2,70}?)\s+"
                   r"(?:is|are|refers to|means|can be defined as)\s+(?P<d>.+)$", re.I),
        re.compile(r"^(?P<c>[A-Za-z][A-Za-z0-9\- ]{2,70}?)\s+"
                   r"(?:divides|uses|allows|provides|enables|consists of|involves)\s+(?P<d>.+)$", re.I),
    ]
    seen, final = set(), []
    for sentence in extract_sentences(text):
        for pat in patterns:
            m = pat.match(sentence.strip())
            if not m:
                continue
            if not m.group("c").strip()[:1].isupper():
                break      # sentence fragment from a wrapped PDF line
            concept = clean_concept(m.group("c"))
            if concept and len(concept.split()) <= 6 and is_good_concept(concept):
                key = normalize(concept)
                if key not in seen:
                    seen.add(key)
                    final.append((concept, sentence))
            break
    return final


def extract_bullet_concepts(text: str) -> List[str]:
    out = []
    for ln in clean_text(text).split("\n"):
        m = re.match(r"^(?:[-*\u2022]|\d+(?:\.\d+)*[\.)\-:])\s*(.+)$", ln.strip())
        if not m:
            continue
        cand = re.sub(r"[.;:,]+$", "", m.group(1).strip())
        if cand and len(cand.split()) <= 10:
            out.append(cand)
    return unique_concepts(out)


def extract_phrase_concepts(text: str) -> List[str]:
    """Repeated Capitalised Phrases (e.g. 'Message Passing Interface')."""
    counts: Dict[str, int] = {}
    for sentence in extract_sentences(text):
        for m in re.finditer(r"\b[A-Z][A-Za-z\-]*(?:\s+[A-Z][A-Za-z\-]*){1,3}\b", sentence):
            phrase = m.group(0).strip()
            counts[phrase] = counts.get(phrase, 0) + 1
    ranked = sorted(counts, key=lambda p: (-counts[p], p))
    return unique_concepts(ranked)


def extract_concepts(text: str) -> List[str]:
    text = clean_text(text)
    if not text:
        return []
    ordered = [c for c, _ in extract_definition_concepts(text)]
    ordered += extract_heading_concepts(text)
    ordered += extract_bullet_concepts(text)
    ordered += extract_phrase_concepts(text)
    pool = unique_concepts(ordered)
    haystack = " " + normalize(text) + " "

    def freq(c: str) -> int:
        return min(haystack.count(" " + normalize(c) + " "), 20)

    # topics the lecture keeps coming back to rank first
    ranked = sorted(range(len(pool)), key=lambda i: (-freq(pool[i]), i))
    return [pool[i] for i in ranked][:30]


def normalize_question_type(question_type: str) -> str:
    value = normalize(question_type)
    return TYPE_ALIASES.get(value, value)


def normalize_question_types(question_types) -> Dict[str, int]:
    if question_types is None:
        return {}
    result: Dict[str, int] = {}
    items = question_types.items() if isinstance(question_types, dict) else \
        [(i, 1) for i in question_types]
    for raw_type, raw_count in items:
        qtype = normalize_question_type(str(raw_type))
        if qtype not in SUPPORTED_TYPES:
            raise ValueError(f"Unsupported question type: {raw_type}. "
                             f"Supported: {', '.join(sorted(SUPPORTED_TYPES))}")
        try:
            count = int(raw_count)
        except (TypeError, ValueError):
            raise ValueError(f"Invalid quantity for {raw_type}: {raw_count}")
        if count <= 0:
            raise ValueError(f"Question quantity must be greater than zero: {raw_type}")
        result[qtype] = result.get(qtype, 0) + count
    return result


